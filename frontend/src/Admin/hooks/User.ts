// 役割に応じてユーザー名を固定する

// 幹部ロールの場合、名前は常に "幹部" に固定される。
// それ以外の場合は現在の名前をそのまま返す。

// 使用箇所：Admin.tsx の handleNameChange

// @param role - 現在の役割
// @param currentName - 現在のユーザー名
// @returns 確定後のユーザー名

export const getLockedName = (role: string, currentName: string): string => {
    if (role === "幹部") return "幹部";
    return currentName;
};

